-- == 2026-10-21 - UFC REGISTRY NOTE: WHERE THE RECORD IN THE BANNER COMES FROM ==
--
-- ANDY: "update UFC sports registry note and make sure it updates record by
-- itself if we are going to put record".
--
-- The second half was the real gap and it is fixed outside this file:
-- refresh_calibration_notes.py builds the banner's W-L out of
-- surface_records, and it was in NO workflow. It is now a step in
-- daily_card.yml, immediately after compute_surface_records, so the number
-- is rebuilt three times a day from the records that run just wrote.
--
-- This file fills `notes`, which the client does NOT select (verified
-- against the app's sport_registry query: sport, emoji, display_order,
-- active, state, state_message, today_note, tomorrow_note, tab_scope,
-- return_date, ladder_eligible, season_start). So it is an operator note,
-- and the thing worth writing down is which record the banner quotes -
-- because UFC has TWO and they disagree.
--
-- ── TWO RECORDS, ONE SPORT ──────────────────────────────────────────────
-- Measured today from surface_records:
--
--   game_read  lifetime   11-7   61.1%   n=18    +3.0u   <- the banner
--   ufc_sides  lifetime   45-44  50.6%   n=89    -3.1u
--
-- Neither is wrong. `game_read` is what we PUBLISHED - the reads a
-- subscriber actually saw - and `ufc_sides` is every pick the model made,
-- published or not. The published subset is 61.1% on eighteen fights; the
-- model's full output is a coin flip that loses to the juice on
-- eighty-nine. A reader who sees 61.1% and assumes it describes the engine
-- is reading the wrong denominator, which is the same mistake
-- feedback_surface_records_trust_levels records for prop_prime.
--
-- The banner is right to quote the published figure and right to say, as it
-- does, that UFC is "still inside its calibration window (18 of 250 graded
-- reads), so treat a UFC tier as a lighter claim." n=18 cannot separate
-- 61% from 50% - the 95% interval on 11-7 runs roughly 36% to 83%.
--
-- ── AND THE ABSTENTION IS NOT A FAULT ───────────────────────────────────
-- B83, 2026-10-20: forcing the engine's most confident tier through would
-- have LOST money. Graded at real median decimal prices over 95 picks,
-- ev_tier PRIME is 7-10 (ROI -37.5%) and tier_winner PRIME wins often while
-- losing money (19-10, ROI -13.5%) - favourite-picking at bad prices. So a
-- fight-week card showing zero plays is the engine declining a tier that
-- does not beat its price, and the banner now says so in words.

UPDATE public.sport_registry
   SET notes = 'OPERATOR NOTE (2026-10-21). The W-L in state_message is '
               'AUTO-GENERATED by refresh_calibration_notes.py from '
               'surface_records(sport=UFC, surface=game_read) and is '
               'rebuilt by daily_card.yml three times a day. Do not '
               'hand-edit the record into this banner - the script owns UFC '
               '(OWNED tuple) and will overwrite it. '
               'TWO RECORDS EXIST AND THEY DISAGREE: game_read is what we '
               'PUBLISHED (11-7, 61.1%, n=18, +3.0u) and ufc_sides is every '
               'pick the model made (45-44, 50.6%, n=89, -3.1u). The banner '
               'quotes the published one, which is correct, but n=18 gives a '
               '95% interval of roughly 36-83% - it cannot tell 61% from a '
               'coin flip, which is why the calibration caveat stays until '
               'n=250. '
               'ZERO PLAYS ON A FIGHT CARD IS NOT A FAULT: per B83, forcing '
               'the top tier through would have lost money (ev_tier PRIME '
               '7-10, ROI -37.5% over 95 graded at real prices). '
               'UFC has no season_start/season_end on purpose - tab_scope is '
               'weekly and the card is the unit, not the calendar.',
       updated_at = now()
 WHERE sport = 'UFC';

DO $$
DECLARE n INT; has_note BOOLEAN;
BEGIN
  SELECT COUNT(*), bool_and(notes IS NOT NULL) INTO n, has_note
    FROM public.sport_registry WHERE sport = 'UFC';
  IF n <> 1 THEN
    RAISE EXCEPTION 'expected exactly 1 UFC sport_registry row, found %', n;
  END IF;
  IF NOT has_note THEN
    RAISE EXCEPTION 'UFC notes did not write';
  END IF;
  RAISE NOTICE 'UFC operator note written; state_message left alone (the '
               'script owns it)';
END $$;
