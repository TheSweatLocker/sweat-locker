-- == 2026-10-21 - DROP 160 MB OF DUPLICATE INDEXES ON line_history ==
--
-- Runs as an ordinary migration. The earlier draft used DROP INDEX
-- CONCURRENTLY, which hits the same ERROR 25001 as 20261021j did - it cannot
-- run inside a transaction block, and several statements in one file are
-- wrapped in one. CONCURRENTLY is not needed to DROP an index: unlike
-- building one, dropping is a catalog update with no data rewrite, so the
-- lock is held for milliseconds rather than for the length of a scan.
--
-- lock_timeout is set so that if the pollers are mid-insert and the lock
-- cannot be taken quickly, this FAILS instead of queueing writes behind
-- itself. A failed migration is re-runnable; a stalled write path during a
-- slate is not. Re-run it if it times out.
--
-- ── WHAT AND WHY ─────────────────────────────────────────────────────────
-- Confirmed from the catalog, not from a report. 20261021h's duplicate check
-- was broken - it grouped on pg_get_indexdef(), which embeds the index NAME,
-- so identical-column indexes could never match and it reported zero groups.
-- 20261021i fixed the grouping to column list + operator classes +
-- uniqueness + predicate, and the pairs are real:
--
--   idx_line_history_captured_at      btree (captured_at DESC)
--   line_history_captured_at_idx      btree (captured_at)              80 MB
--
--   line_history_sport_commence_idx   btree (sport, commence_time DESC)
--   line_history_sport_upcoming_idx   btree (sport, commence_time DESC) 79 MB
--
-- The second pair is byte-identical. The first differs only in declared sort
-- direction, and a btree can be scanned backwards, so a single-column ASC
-- index serves ORDER BY ... DESC equally well.
--
-- THIS IS AN IO FIX, NOT A STORAGE ONE. line_history takes about 235,000
-- inserts a day (2.45M lifetime) and EVERY index on the table is updated on
-- EVERY insert. A redundant index is write amplification charged per row,
-- forever, against the same budget the reads are draining.
--
-- WHICH SURVIVES: the conventionally-named one of each pair. Neither member
-- appears in get_io_audit's never-scanned list, which is what redundancy
-- looks like - the planner picks one arbitrarily and the other still pays
-- the write cost. Keeping either is equivalent.
--
-- idx_line_history_game_date goes too, on evidence: this database's
-- pg_stat_database.stats_reset is NULL, so counters have NEVER been cleared
-- and its idx_scan = 0 is an all-time zero rather than an artefact of a
-- recent reset. That is the one condition that makes "unused" safe to act
-- on, and it is why stats_age_hours was added to the audit before any index
-- was dropped. The other 225 never-scanned indexes (84 MB) are left for a
-- pass that checks each for a nightly-only caller.
--
-- NOT TOUCHED, deliberately: the duplicate UNIQUE indexes on
-- mlb_game_results(game_id) and mlb_game_context(game_id). One of each pair
-- almost certainly backs a UNIQUE CONSTRAINT, and DROP INDEX refuses with
-- "cannot drop index ... because constraint ... requires it", which would
-- abort this file. 864 kB and 80 kB is not worth it, and they need the
-- constraint dropped rather than the index.

SET LOCAL lock_timeout = '5s';

DROP INDEX IF EXISTS public.idx_line_history_captured_at;
DROP INDEX IF EXISTS public.line_history_sport_upcoming_idx;
DROP INDEX IF EXISTS public.idx_line_history_game_date;
