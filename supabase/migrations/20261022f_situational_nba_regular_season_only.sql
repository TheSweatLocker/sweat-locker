FROM public.team_situational_records_full
-- 2026-10-21: season is TEXT now, so this comparison is lexical. Correct
-- for these two sports because their label is always a bare 4-digit year
-- ('2025' < '2026'), and it must NOT be written as season::INT < 2026 -
