-- == 2026-10-22f · NBA RECORDS COUNT ONLY THE REGULAR SEASON ==
--
-- The last step of the denominator fix. 20261022d added season_type to
-- nba_game_results and the backfill filled 2,840 of 2,843 rows from ESPN;
-- this is the filter that finally uses it.
--
-- WHAT THE RECORDS WERE. team_situational_records, 2025-26, ml, overall:
-- all 30 of 30 teams over 82 games, range 84..110, home/road 42..56 against
-- a real 41. The card showed Cleveland 61-43 and Philadelphia 51-47, which
-- are 104 and 98 games.
--
-- WHAT THIS REPLACES. The NBA blocks carried two HEURISTICS written on
-- 10-21 precisely because season_type did not exist yet:
--   * a preseason gate keyed on sport_registry.season_start, scoped to the
--     CURRENT season only - so every prior season's exhibitions stayed in
--   * an opponent-membership check against nba_team_stats, which caught the
--     14 games against Team Stars / World / Guangzhou / Melbourne
-- Neither could touch the playoffs, the play-in, or the Cup final, which is
-- where most of the overflow actually was.
--
-- season_type subsumes both and is stated by the feed rather than inferred:
--   regular 2514 · postseason 169 · preseason 136 · playin 12 · allstar 7 ·
--   cup_final 2 · null 3
--
-- THE PROOF IT IS RIGHT. Both completed seasons now come to exactly 1,230
-- regular-season games at exactly 82 per team for all 30 - which is
-- 30 x 82 / 2, the arithmetic definition. Not "closer"; exact.
--
-- Two of those phases needed the note headline rather than ESPN's own
-- season.type, which files both as type 2 'regular-season':
--   the ALL-STAR games ("NBA All-Star - Round Robin")
--   the NBA CUP FINAL ("NBA Cup Championship", neutral site) - the one Cup
--   game that does not count toward the 82, which is why exactly two teams
--   per season sat at 83 until it was labelled
--
-- GENERATED BY TRANSFORM from 20261021p, not written by hand - the same
-- discipline that file's own header insists on, because a hand-rewrite of
-- this matview previously broke the per-market sequencing (seq_spread /
-- seq_ml / seq_total, which make L5 and L10 count the last 5 or 10 games in
-- which THAT market resolved). Exactly two hunks changed, both NBA WHERE
-- clauses; the aggregation tail is byte-identical.
--
-- NHL, MLB and NCAAB still have this defect and are NOT touched here. Their
-- results tables have no season_type column, and their game_ids cannot be
-- joined to ESPN without matching team names across two feeds - the defect
-- that cost STL every odd and tendency for weeks. They get their own
-- migration once that join is built and verified.

