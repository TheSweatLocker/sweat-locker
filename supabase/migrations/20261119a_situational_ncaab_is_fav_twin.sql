-- == 2026-11-19 · NCAAB is_fav READS THE POPULATED TWIN ==
--
-- Andy: "ensure every sport is surfacing correct situational records and
-- ensure that fuck up isnt happening anymore."
--
-- THE DEFECT. ncaab_game_results holds the closing moneyline in TWO column
-- pairs, and the matview read the empty one:
--
--     close_home_ml / close_away_ml      0 of 626 scored 2026-27 rows
--     home_ml_close / away_ml_close    589 of 626  (94.1%)
--
-- is_fav was therefore NULL on every NCAAB row. NULL IS NOT FALSE: both
-- `WHERE is_fav` and `WHERE NOT is_fav` exclude it, so the as_fav and
-- as_dog aggregates produced NO ROWS AT ALL - for all 362 teams, in every
-- market. The card drops a filter row when neither team has data for it, so
-- every NCAAB game card has been showing THREE filter rows where NHL and
-- NBA show four, with nothing on screen to say a row was missing.
--
-- Measured, per sport, in team_situational_records:
--     NHL    as_fav  93   as_dog  93
--     NBA    as_fav 249   as_dog 255
--     NCAAB  as_fav   0   as_dog   0     <-- this
--
-- SAME CLASS as the NHL puck line found the same morning:
-- nhl_game_results.close_puckline was NULL for the whole 2026-11-07 slate
-- while nhl_game_context.close_spread held the line. A column with a
-- populated twin reads as "no data", and nothing downstream can tell the
-- difference between genuinely absent and merely unselected.
--
-- COALESCE, not a column swap, deliberately: whichever pair a season or a
-- backfill happened to fill, is_fav resolves. It cannot regress to NULL
-- unless BOTH pairs are empty, which is a real data gap rather than a
-- reader pointed at the wrong name.
--
-- NOT CHANGED HERE, and why:
--   NBA   keeps season_type = 'regular'. Its 182 uncounted 2026-27 games
--         are NULL season_type, not a twin-column problem, and relaxing the
--         gate would re-admit the preseason the gate exists to exclude.
--         Fixed by filling the column (backfill_nba_season_type.py).
--   NHL   keeps close_puckline. Its gap is in the RESULTS data, not in this
--         reader; those 12 rows get the line and the grade backfilled.
--   MLB   keeps close_spread for is_fav. 272 of 2,409 are NULL and MLB is
--         out of season; that is logged, not papered over here.
--
-- GENERATED BY TRANSFORM from 20261022g. Exactly two hunks changed, both
-- NCAAB is_fav expressions; every other byte is identical, per that file's
-- own warning that these migrations do a FULL CREATE and have twice
