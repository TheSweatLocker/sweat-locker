-- │ RUN THE SINGLE STATEMENT BELOW ON ITS OWN.                           │
-- │                                                                      │
-- │ The first version of this file failed with                           │
-- │   ERROR 25001: CREATE INDEX CONCURRENTLY cannot run inside a         │
-- │   transaction block                                                  │
-- │ because it carried a NOTIFY as well, and more than one statement in  │
-- │ the SQL editor is wrapped in an implicit transaction. CONCURRENTLY   │
-- │ cannot live inside one. The NOTIFY is also pointless here: it        │
-- │ reloads PostgREST's SCHEMA cache, and an index is not part of the    │
-- │ schema PostgREST exposes. So it is gone and this file is now one     │
-- │ statement.                                                           │
-- │                                                                      │
-- │ If it STILL reports 25001, the runner is wrapping even a single      │
-- │ statement. Then use the non-concurrent form at the bottom and read   │
-- │ the trade-off first.                                                 │
-- └──────────────────────────────────────────────────────────────────────┘
--
-- get_io_audit named the drain. One shape:
--
--     694.69 GiB read from disk · 129,297 calls · 202ms mean · 26,134s total
--
-- That is the Disk IO Budget, by itself - five times the next consumer. It
-- is detect_line_movement's detect_steam() read:
--
--     sport = $1 AND captured_at >= $2
--     ORDER BY captured_at ASC
--     LIMIT 1000 OFFSET {0,1000,...,19000}
--
-- 20261021b ADDED THE WRONG INDEX. It created
-- (sport, market, side, commence_time DESC), because the advisor report
-- described the hot shape as "sport + commence_time lower bound". The actual
-- query filters and orders on **captured_at**, a different column with a
-- different meaning: commence_time is when the GAME starts, captured_at is
-- when the QUOTE was polled. Nothing covered (sport, captured_at), so all
-- 129,297 calls fell back to scanning. I took the advisor's wording for the
-- caller's behaviour instead of reading the caller.
--
-- This index serves all three parts of that query at once: `sport` equality
-- narrows, `captured_at` serves the range predicate AND the ORDER BY, so the
-- sort disappears too. Equality column first, range column last - the
-- reverse cannot use the equality to narrow.
--
-- NOT A COMPLETE FIX ALONE. The same callers paginated with deep OFFSET,
-- which re-walks every row before the offset on each page (~210,000
-- row-reads to return 20,000; market_line._page was ~7.3M at its cap). Both
-- are converted to keyset pagination in c9cf5081. The index makes each page
-- cheap; keyset stops the number of pages multiplying.

CREATE INDEX CONCURRENTLY IF NOT EXISTS line_history_sport_captured_idx
  ON public.line_history (sport, captured_at);

